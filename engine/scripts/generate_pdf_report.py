def page_coach_letter(scope, sub, d, matches, history):
    """Page 1 of the SEASON stat card: the coach's letter to the team — the last
    game's story, league standing, advice, batting/bowling reads, then a word to
    each player. The newest letter of the season whose fingerprint still matches
    (coach_notes.yaml -> letters, written per game via /ai-coach); none -> the rule
    engines' fallback (the end-of-run warnings say which games need a letter)."""
    _, entry = coach.latest_letter(matches, LETTERS, history)
    if entry:   # AI-written HTML: formatting tags only before the headless browser sees it
        sections = [{"title": s.get("title", ""), "html": safe_html(s.get("html"))}
                    for s in entry["sections"]]
        players = [{"name": p.get("name", ""), "note": safe_html(p.get("note"))}
                   for p in entry.get("players") or []]
    else:
        sections, players = coach_letter_fallback(d), []
    body = "".join(
        f"<div class='lsec'><div class='lsect'>{esc(s['title'])}</div>{s['html']}</div>"
        for s in sections)
    if players:
        items = "".join(f"<div class='pgi'><b>{esc(p['name'])}</b> — {p['note']}</div>"
                        for p in players)
        # say so when the notes cover only the last game's players (the ai-coach rule);
        # a letter that also covers absentees (e.g. a season wrap-up) keeps the plain title
        last = d["team"]["games"][-1]["date"] if d["team"]["games"] else None
        played_last = all(any(g["date"] == last for g in d["gamelog"].get(p["name"], []))
                          for p in players)
        ptitle = ("A word to each player who played the last game" if played_last
                  else "A word to each player")
        body += (f"<div class='lsec'><div class='lsect'>{ptitle}</div>"
                 f"<div class='pgrid'>{items}</div></div>")
    else:
        body += enote("player-by-player notes arrive with the next coach refresh")
    disc = (f"<div class='aidisc'>This page was AI-generated ({esc(paths.TEAM_NAME)} AI Coach) from the "
            "season's verified ball-by-ball records and the league table — the numbers "
            "are checked, the opinions are the coach's own.</div>")
    return f"""<section class='page'>{header(scope, 'Letter from the AI Coach', sub)}
<div class='block letter'>{body}</div>
{disc}
</section>"""


