def line_chart(games, w=706, h=180):
    """Two lines over the game sequence: team total (brand) vs opponent (muted)."""
    if not games:
        return ""
    pad_l, pad_r, pad_t, pad_b = 30, 12, 14, 22
    iw, ih = w - pad_l - pad_r, h - pad_t - pad_b
    n = len(games)
    ymax = max([g["total"] for g in games] + [g["against"] for g in games] + [20])
    ymax = (int(ymax / 20) + 1) * 20

    def X(i):
        return pad_l + (iw * i / (n - 1) if n > 1 else iw / 2)

    def Y(v):
        return pad_t + ih - (v / ymax * ih)

    # gridlines
    grid = []
    for gy in range(0, ymax + 1, 40):
        y = Y(gy)
        grid.append(f"<line x1='{pad_l}' y1='{y:.1f}' x2='{w-pad_r}' y2='{y:.1f}' "
                    f"stroke='{PAL['grid']}' stroke-width='1'/>")
        grid.append(f"<text x='{pad_l-6}' y='{y+3:.1f}' text-anchor='end' "
                    f"font-size='9' fill='{PAL['muted']}'>{gy}</text>")

    def poly(key, color, wid):
        pts = " ".join(f"{X(i):.1f},{Y(g[key]):.1f}" for i, g in enumerate(games))
        dots = "".join(f"<circle cx='{X(i):.1f}' cy='{Y(g[key]):.1f}' r='2.6' fill='{color}'/>"
                       for i, g in enumerate(games))
        return f"<polyline points='{pts}' fill='none' stroke='{color}' stroke-width='{wid}'/>{dots}"

    # x labels (thin them out)
    step = max(1, n // 10)
    xlab = []
    for i, g in enumerate(games):
        if i % step == 0 or i == n - 1:
            xlab.append(f"<text x='{X(i):.1f}' y='{h-6}' text-anchor='middle' "
                        f"font-size='8' fill='{PAL['muted']}'>{mmdd(g['date'])}</text>")
    return (f"<svg viewBox='0 0 {w} {h}' width='100%' style='display:block'>"
            f"{''.join(grid)}{poly('against', PAL['muted'], 1.6)}"
            f"{poly('total', PAL['brand'], 2.2)}{''.join(xlab)}</svg>")


def stack_rows(rows, seglist_fn, w=340, rowh=20, label_w=78, maxlabel=8):
    """Horizontal stacked bars. rows -> (label, [(segname,count,color),...])."""
    prepared = [(lab, seglist_fn(r)) for lab, r in rows]
    maxtot = max((sum(c for _, c, _ in segs) for _, segs in prepared), default=1) or 1
    barw = w - label_w - 34
    out = []
    for i, (lab, segs) in enumerate(prepared):
        y = i * rowh
        tot = sum(c for _, c, _ in segs)
        x = label_w
        segsvg = []
        for _, c, col in segs:
            if c <= 0:
                continue
            bw = barw * c / maxtot
            segsvg.append(f"<rect x='{x:.1f}' y='{y+3}' width='{max(bw-0.8,0):.1f}' height='{rowh-8}' "
                          f"rx='1.5' fill='{col}'/>")
            x += bw
        out.append(f"<text x='0' y='{y+rowh/2+3}' font-size='9.5' fill='{PAL['ts']}'>{esc(lab[:maxlabel])}</text>"
                   f"{''.join(segsvg)}"
                   f"<text x='{x+4:.1f}' y='{y+rowh/2+3}' font-size='9' fill='{PAL['muted']}'>{tot}</text>")
    hgt = len(prepared) * rowh + 2
    return f"<svg viewBox='0 0 {w} {hgt}' width='100%' style='display:block'>{''.join(out)}</svg>"


