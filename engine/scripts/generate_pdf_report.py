def dismissal_bar(obt, tot):
    """Full-length stacked bar: each dismissal type is a coloured segment sized by its
    share of outs, with the % printed inside. Any dismissal outside the four named types
    falls into a neutral 'other' segment so the bar always accounts for every out."""
    if not tot:
        return "<span class='dnone'>—</span>"
    segs, covered = [], 0
    for name, col in DISMISS_GROUPS:
        c = obt.get(name, 0)
        covered += c
        if c <= 0:
            continue
        pct = round(100 * c / tot)
        lbl = f"{pct}%" if pct >= 8 else ""       # hide the label on segments too thin to fit it
        segs.append(f"<span class='dseg' style='flex:{c};background:{col}' "
                    f"title='{esc(name)} · {pct}%'>{lbl}</span>")
    other = tot - covered
    if other > 0:
        pct = round(100 * other / tot)
        lbl = f"{pct}%" if pct >= 8 else ""
        segs.append(f"<span class='dseg' style='flex:{other};background:{PAL['muted']}' "
                    f"title='other · {pct}%'>{lbl}</span>")
    return f"<div class='dbar'>{''.join(segs)}</div>"


def wkt_bar(wt):
    """Full-length stacked bar of a bowler's wicket types, sized by count with each type's
    count and share of wickets printed inside its segment (the Wkts column carries the total)."""
    tot = sum(wt.get(n, 0) for n, _ in WKT_GROUPS)
    if not tot:
        return "<span class='dnone'>—</span>"
    segs = []
    for name, col in WKT_GROUPS:
        c = wt.get(name, 0)
        if c <= 0:
            continue
        pct = round(100 * c / tot)
        # count + % when the segment is wide enough, % only when narrower, else nothing
        lbl = f"{c} · {pct}%" if pct >= 22 else (f"{pct}%" if pct >= 10 else "")
        segs.append(f"<span class='dseg' style='flex:{c};background:{col}' "
                    f"title='{esc(name)} · {c} ({pct}%)'>{lbl}</span>")
    return f"<div class='dbar'>{''.join(segs)}</div>"


def donut(items, center_big, center_sub, size=124):
    """Donut chart with % labels inside segments, a big total in the hole, and a
    stacked legend beside it. items -> [(label, count, colour)]."""
    items = [(l, c, col) for l, c, col in items if c > 0]
    tot = sum(c for _, c, _ in items)
    if not tot:
        return enote("no data yet")
    cx = cy = size / 2
    R, r = size / 2 - 1, (size / 2) * 0.60
    segs, a = [], -math.pi / 2
    for lab, c, col in items:
        frac = c / tot
        a2 = a + frac * 2 * math.pi
        if frac >= 0.999:   # single-type edge case: a full ring, not an arc path
            segs.append(f"<circle cx='{cx}' cy='{cy}' r='{(R + r) / 2:.1f}' fill='none' "
                        f"stroke='{col}' stroke-width='{R - r:.1f}'/>")
        else:
            x0, y0 = cx + R * math.cos(a), cy + R * math.sin(a)
            x1, y1 = cx + R * math.cos(a2), cy + R * math.sin(a2)
            x2, y2 = cx + r * math.cos(a2), cy + r * math.sin(a2)
            x3, y3 = cx + r * math.cos(a), cy + r * math.sin(a)
            large = 1 if frac > 0.5 else 0
            segs.append(f"<path d='M{x0:.1f},{y0:.1f} A{R:.1f},{R:.1f} 0 {large} 1 {x1:.1f},{y1:.1f} "
                        f"L{x2:.1f},{y2:.1f} A{r:.1f},{r:.1f} 0 {large} 0 {x3:.1f},{y3:.1f} Z' "
                        f"fill='{col}' stroke='{PAL['surface']}' stroke-width='1'/>")
        if frac >= 0.09:    # % label inside the segment when it's wide enough to fit
            am, lr = (a + a2) / 2, (R + r) / 2
            segs.append(f"<text x='{cx + lr * math.cos(am):.1f}' y='{cy + lr * math.sin(am) + 2.6:.1f}' "
                        f"text-anchor='middle' font-size='8.5' font-weight='700' fill='#fff'>"
                        f"{round(100 * frac)}%</text>")
        a = a2
    segs.append(f"<text x='{cx}' y='{cy - 1:.1f}' text-anchor='middle' font-size='17' "
                f"font-weight='800' fill='{PAL['ink']}'>{center_big}</text>")
    segs.append(f"<text x='{cx}' y='{cy + 11:.1f}' text-anchor='middle' font-size='7.5' "
                f"fill='{PAL['muted']}'>{esc(center_sub)}</text>")
    leg = "".join(f"<span class='lg'><i style='background:{col}'></i>{esc(lab)} "
                  f"<b>{round(100 * c / tot)}%</b> · {c}</span>" for lab, c, col in items)
    return (f"<div class='dwrap'><svg viewBox='0 0 {size} {size}' width='{size}' height='{size}'>"
            f"{''.join(segs)}</svg><div class='dleg'>{leg}</div></div>")


