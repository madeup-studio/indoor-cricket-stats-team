def _score_recs(d):
    """Record cards (one each, not top 5): our highest/lowest total, opponents'
    highest/lowest. Returns the card list; the page wraps it in a recs4/recs5 grid."""
    t = d["team"]
    hi, lo = t["high_score"], t["low_score"]
    ohi = d["opp_highest"][0] if d["opp_highest"] else None
    olo = d["opp_lowest"][0] if d["opp_lowest"] else None
    cards = []
    if hi:
        cards.append(rec_card("Our highest score", num(hi["total"]),
                              f"vs {hi['opp']} · {hi['date']}", PAL["good"]))
    if lo:
        cards.append(rec_card("Our lowest score", num(lo["total"]),
                              f"vs {lo['opp']} · {lo['date']}", PAL["bad"]))
    if ohi:
        cards.append(rec_card("Highest against us", num(ohi[0]),
                              f"{ohi[1]} · {ohi[2]}", PAL["bad"]))
    if olo:
        cards.append(rec_card("Lowest against us", num(olo[0]),
                              f"{olo[1]} · {olo[2]}", PAL["good"]))
    return cards


def _win_streak_card(games):
    """Longest run of consecutive wins (ties break it) as a record card; empty
    string if there is no win yet."""
    best = cur = 0
    cur_start = span = None
    for g in games:
        if g["outcome"] == "win":
            if cur == 0:
                cur_start = g["date"]
            cur += 1
            if cur > best:
                best, span = cur, (cur_start, g["date"])
        else:
            cur = 0
    if not best:
        return ""
    sub = span[0] if span[0] == span[1] else f"{span[0]} → {span[1]}"
    if cur == best:   # the record streak is the live one — still running
        sub += " · ongoing"
    return rec_card("Longest win streak", f"{best}<span class='x'> win{'s' if best != 1 else ''}</span>",
                    sub, PAL["good"])


