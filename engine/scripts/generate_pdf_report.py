def _photo_uri(name):
    """Player photo placeholder: drop photos/<name-slug>.jpg|png in the team folder and
    it's embedded automatically; until then the initials avatar is shown."""
    pdir = os.path.join(paths.TEAM_DIR, "photos")
    for ext, mime in (("jpg", "image/jpeg"), ("jpeg", "image/jpeg"), ("png", "image/png")):
        p = os.path.join(pdir, f"{slug(name)}.{ext}")
        if os.path.exists(p):
            with open(p, "rb") as f:
                return f"data:{mime};base64," + base64.b64encode(f.read()).decode()
    return None


