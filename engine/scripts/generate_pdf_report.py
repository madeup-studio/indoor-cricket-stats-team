def footer(pg, total, scope, gen):
    return (f"<footer><span>{esc(paths.TEAM_NAME)} · {esc(scope)} · ball-by-ball verified · generated {gen}</span>"
            f"<span>page {pg} / {total}</span></footer>")


def slug(s):
    import re
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def render_doc(pages, scope, out_pdf, gen):
    """Wrap pages into a print-styled HTML doc, footer them, and print to PDF via Edge/Chrome."""
    total = len(pages)
    body = [p.replace("</section>", footer(i, total, scope, gen) + "</section>")
            for i, p in enumerate(pages, 1)]
    doc = (f"<!doctype html><html><head><meta charset='utf-8'>"
           f"<title>{esc(paths.TEAM_NAME)} Stats — {esc(scope)}</title><style>{CSS}</style></head>"
           f"<body>{''.join(body)}</body></html>")
    os.makedirs(BUILD_DIR, exist_ok=True)
    hp = os.path.join(BUILD_DIR, slug(scope) + ".html")
    with open(hp, "w", encoding="utf-8") as f:
        f.write(doc)
    if not BROWSER:
        print(f"!! no Edge/Chrome found -> skipped {os.path.basename(out_pdf)} (HTML is at {hp}). "
              f"Install Chrome or set PDF_BROWSER to a Chromium-based browser.")
        return
    before = os.path.getmtime(out_pdf) if os.path.exists(out_pdf) else 0
    r = subprocess.run([BROWSER, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                        "--print-to-pdf-no-header", f"--print-to-pdf={out_pdf}",
                        "file:///" + hp.replace("\\", "/")],
                       timeout=120, capture_output=True)
    after = os.path.getmtime(out_pdf) if os.path.exists(out_pdf) else 0
    if r.returncode == 0 and after > before:
        print("wrote", out_pdf)
    else:
        print(f"!! COULD NOT WRITE {out_pdf}\n   -> it is probably OPEN in a PDF viewer (file locked). "
              f"Close it and re-run.")


def _doc_season(scope, sub, d, out_pdf, gen, matches, history):
    """SEASON stat card. Season-card-only page changes are wired up here.
    Opens with the Letter from the Coach — the only page carrying AI content —
    unless the team switched the coach off (team.yaml coach.enabled: false)."""
    pages = ([page_coach_letter(scope, sub, d, matches, history)] if paths.COACH["enabled"] else [])
    pages += [page_team_season(scope, sub, d), page_batting(scope, sub, d), page_bowling(scope, sub, d)]
    pages += [page_player(scope, sub, d, i) for i in range(len(d["allround"]))]
    render_doc(pages, sub, out_pdf, gen)


def _doc_alltime(scope, sub, d, out_pdf, gen):
    """ALL-TIME stat card. All-time-card-only page changes are wired up here.
    No coach letter — coach content is a season-card feature."""
    pages = [page_team_alltime(scope, sub, d), page_batting(scope, sub, d), page_bowling(scope, sub, d)]
    pages += [page_player(scope, sub, d, i) for i in range(len(d["allround"]))]
    render_doc(pages, sub, out_pdf, gen)


def main():
    seasons, allm, R = RD.load_all()
    gen = os.environ.get("REPORT_DATE", datetime.date.today().isoformat())
    latest = seasons[-1][0] if seasons else None

    # one deterministic season stat card per season -> lives in that season's folder
    for sd, label, ms in seasons:
        tag = " · current" if sd == latest else ""
        _doc_season(f"{label}{tag}", f"Season · {label}", RD.build(ms, R),
                    os.path.join(sd, f"{paths.TEAM}-{slug(label)}.pdf"), gen, ms, allm)

    # combined all-time stat card -> lives in the team folder
    _doc_alltime("All-time", f"All-time · {len(seasons)} seasons", RD.build(allm, R, alltime=True),
                 os.path.join(paths.TEAM_DIR, f"{paths.TEAM}-all-time.pdf"), gen)

    todo = [r for r in coach.status(seasons, LETTERS) if r["state"] != "ok"]
    if paths.COACH["enabled"] and todo:
        print()
        for r in todo:
            print(f"!! coach letter {r['state']}: {r['key']} {r['fp']}")
        print("   Ask Claude to write them (the ai-coach skill), oldest first.")


